// Static build: copies src/ to dist/, expands <!--#include name--> partials and
// fills {{token}} placeholders from config.json. No dependencies.
//   node build.mjs            → dist/         (for a web server: clean URLs like /services/)
//   node build.mjs --static   → dist-static/  (open index.html by double-clicking: no server needed)
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, copyFileSync, rmSync } from "node:fs";
import { join, dirname, extname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const src = join(root, "src");
const STATIC = process.argv.includes("--static");
const dist = join(root, STATIC ? "dist-static" : "dist");
const config = JSON.parse(readFileSync(join(root, "config.json"), "utf8"));
// Preview mode: while the details are still samples, keep the site out of search engines and say so on every page.
const PREVIEW = String(config.preview) !== "false";
config.robotsMeta = PREVIEW ? '<meta name="robots" content="noindex, nofollow">' : "";
config.robotsRule = PREVIEW ? "Disallow: /" : "Allow: /\nDisallow: /api/";
config.previewBanner = PREVIEW
  ? '<div class="preview-banner" role="note">Preview website: names, phone numbers and prices are samples, not a real funeral home.</div>' : "";

const fill = (text) =>
  text.replace(/\{\{(\w+)\}\}/g, (m, key) => {
    if (!(key in config)) throw new Error(`Unknown token ${m}`);
    return config[key];
  });

const partial = (name) => readFileSync(join(src, "partials", `${name}.html`), "utf8");

// Pages that don't start with <!doctype> are wrapped in partials/layout.html.
// Metadata comes from leading comments:  <!--title: ...-->  <!--description: ...-->  <!--head: extra-->
function wrap(html, rel) {
  if (/^\s*<!doctype/i.test(html)) return html;
  const meta = {};
  html = html.replace(/^\s*<!--(\w+):([\s\S]*?)-->\s*/g, (_, k, v) => { meta[k] = v.trim(); return ""; });
  while (/^\s*<!--(\w+):/.test(html)) html = html.replace(/^\s*<!--(\w+):([\s\S]*?)-->\s*/, (_, k, v) => { meta[k] = v.trim(); return ""; });
  const path = "/" + rel.replace(/\\/g, "/").replace(/index\.html$/, "");
  return partial("layout")
    .replace(/%TITLE%/g, () => meta.title || config.name)
    .replace(/%DESCRIPTION%/g, meta.description || "")
    .replace(/%PATH%/g, path)
    .replace("%HEAD%", () => meta.head || "")
    .replace("%BODY%", () => html);
}

// --static: turn site-root links ("/services/", "/assets/…") into relative file links
// ("../services/index.html") so pages work from file:// and any sub-folder.
function relativise(html, rel) {
  const depth = rel.replace(/\\/g, "/").split("/").length - 1;
  const up = depth ? "../".repeat(depth) : "./";
  const fix = (url) => {
    if (!url.startsWith("/") || url.startsWith("//")) return url;
    const [path, hash = ""] = url.slice(1).split("#");
    const file = path === "" || path.endsWith("/") ? path + "index.html" : path;
    return up + file + (hash ? "#" + hash : "");
  };
  return html
    .replace(/\b(href|src|action)="([^"]*)"/g, (_, a, v) => `${a}="${fix(v)}"`)
    .replace(/\b(srcset|imagesrcset)="([^"]*)"/g, (_, a, v) =>
      `${a}="${v.split(",").map((part) => { const [u, ...rest] = part.trim().split(/\s+/); return [fix(u), ...rest].join(" "); }).join(", ")}"`);
}

function render(html) {
  // Partials may themselves contain includes (one level is enough here).
  for (let i = 0; i < 2; i++) html = html.replace(/<!--#include (\w[\w-]*)-->/g, (_, n) => partial(n));
  return fill(html);
}

// The Cloudflare Worker cannot read files, so it imports the schema as a JS string. Regenerated on every build
// (Cloudflare runs this build before each deploy), so db/schema.sql stays the one source of truth.
writeFileSync(join(root, "db", "schema.mjs"),
  "// GENERATED by build.mjs from db/schema.sql. Do not edit: change schema.sql and run `node build.mjs`.\n" +
  `export const SCHEMA = ${JSON.stringify(readFileSync(join(root, "db", "schema.sql"), "utf8"))};\n`);

rmSync(dist, { recursive: true, force: true });
const pages = [];

(function walk(dir) {
  for (const entry of readdirSync(dir)) {
    const from = join(dir, entry);
    const rel = relative(src, from);
    if (rel.startsWith("partials")) continue;
    const to = join(dist, rel);
    if (statSync(from).isDirectory()) { walk(from); continue; }
    mkdirSync(dirname(to), { recursive: true });
    const ext = extname(entry);
    if ([".html", ".xml", ".txt", ".json", ".webmanifest", ".css", ".js"].includes(ext)) {
      writeFileSync(to, ext === ".html" ? (STATIC ? relativise(render(wrap(readFileSync(from, "utf8"), rel)), rel) : render(wrap(readFileSync(from, "utf8"), rel))) : fill(readFileSync(from, "utf8")));
      if (ext === ".html" && entry !== "404.html") pages.push(rel.replace(/index\.html$/, "").replace(/\\/g, "/"));
    } else copyFileSync(from, to);
  }
})(src);

// sitemap.xml generated from the pages that were built
const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  join(dist, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    pages.sort().map((p) => `  <url><loc>${config.domain}/${p}</loc><lastmod>${today}</lastmod></url>`).join("\n") +
    `\n</urlset>\n`
);
// version.txt: open /version.txt on any deploy to see when it was built (and from which commit on Cloudflare).
writeFileSync(join(dist, "version.txt"),
  `built: ${new Date().toISOString()}\ncommit: ${process.env.WORKERS_CI_COMMIT_SHA || process.env.GITHUB_SHA || "local"}\nbranch: ${process.env.WORKERS_CI_BRANCH || process.env.GITHUB_REF_NAME || "local"}\npages: ${pages.length}\n`);
console.log(`Built ${pages.length} pages into ${STATIC ? "dist-static/ (open dist-static/index.html directly)" : "dist/"}`);
